"""Insight -> automation compiler.

Every accepted insight compiles into three artefacts:
  1. `rule`        - a declarative rule Distill's own runner evaluates on fresh data
  2. `n8n_workflow`- an importable n8n workflow JSON (nodes + connections), so the
                     company can run it in an existing automation stack
  3. `skill_md`    - an Agent Skill (SKILL.md with YAML front matter) an AI agent
                     can load to perform the same job conversationally

The n8n output follows n8n's workflow file format: nodes[] with
type/typeVersion/position/parameters and a `connections` map keyed by
source node name, so it imports directly into an existing n8n instance.
"""
from __future__ import annotations

import re
from typing import Any

import pandas as pd

from .insights import _daily, anomalies
from .process_mining import discover


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60]


# --------------------------------------------------------------------------- n8n builders

def _node(name: str, type_: str, x: int, params: dict[str, Any], version: float = 1) -> dict[str, Any]:
    return {"id": slug(name), "name": name, "type": type_, "typeVersion": version, "position": [x, 300],
            "parameters": params}


def _chain(name: str, nodes: list[dict[str, Any]]) -> dict[str, Any]:
    connections = {a["name"]: {"main": [[{"node": b["name"], "type": "main", "index": 0}]]}
                   for a, b in zip(nodes, nodes[1:])}
    return {"name": name, "nodes": nodes, "connections": connections, "active": False,
            "settings": {"executionOrder": "v1"}, "meta": {"generatedBy": "distill"}}


def n8n_for(rule: dict[str, Any], name: str, api_base: str, automation_ref: str) -> dict[str, Any]:
    check_url = f"{api_base}/api/automations/{automation_ref}/evaluate"
    if rule["type"] == "event_bot":
        return _chain(name, [
            _node("On event", "n8n-nodes-base.webhook", 0, {"httpMethod": "POST", "path": slug(name)}, 2),
            _node("Filter trigger activity", "n8n-nodes-base.if", 250, {"conditions": {"string": [
                {"value1": f"={{{{$json.{rule['activity_field']}}}}}", "operation": "equals",
                 "value2": rule["trigger_activity"]}]}}),
            _node("Map fields", "n8n-nodes-base.set", 500, {"keepOnlySet": False, "values": {"string": [
                {"name": "case", "value": f"={{{{$json.{rule['case_field']}}}}}"}]}}, 3),
            _node(rule["replaces_activity"], "n8n-nodes-base.httpRequest", 750,
                  {"method": "POST", "url": "={{$env.TARGET_SYSTEM_URL}}", "sendBody": True,
                   "bodyParametersJson": "={{JSON.stringify($json)}}"}, 4),
        ])
    return _chain(name, [
        _node("Schedule", "n8n-nodes-base.scheduleTrigger", 0,
              {"rule": {"interval": [{"field": "hours", "hoursInterval": rule.get("every_hours", 24)}]}}, 1.2),
        _node("Evaluate in Distill", "n8n-nodes-base.httpRequest", 250, {"method": "POST", "url": check_url}, 4),
        _node("Triggered?", "n8n-nodes-base.if", 500,
              {"conditions": {"boolean": [{"value1": "={{$json.triggered}}", "value2": True}]}}),
        _node("Notify", "n8n-nodes-base.slack", 750,
              {"channel": rule.get("channel", "#ops-alerts"), "text": "={{$json.message}}"}, 2),
    ])


# --------------------------------------------------------------------------- skill builder

def skill_for(name: str, description: str, rule: dict[str, Any], insight_title: str, steps: list[str],
              api_base: str, automation_ref: str) -> str:
    numbered = "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
    return f"""---
name: {slug(name)}
description: {description}
---

# {name}

Generated by Distill from the insight: "{insight_title}".

## When to use
{description}

## How to run the check
`POST {api_base}/api/automations/{automation_ref}/evaluate` returns
`{{"triggered": bool, "message": str, "details": {{...}}}}`.

## Procedure
{numbered}

## Rule definition
```json
{_json(rule)}
```
"""


def _json(obj: Any) -> str:
    import json

    return json.dumps(obj, indent=2, ensure_ascii=False)


# --------------------------------------------------------------------------- compile

def compile_insight(insight: dict[str, Any], profile: dict[str, Any], stats: dict[str, Any]) -> dict[str, Any] | None:
    """Return {name, kind, rule, steps, description, minutes} or None if the insight is not actionable."""
    ev, kind, roles = insight["evidence"], insight["kind"], profile.get("roles", {})
    if kind == "segment_driver":
        metric = ev.get("metric", roles.get("money"))
        rule = {"type": "metric_threshold", "time": roles["time"], "value": None if metric == "count" else metric,
                "filter": {ev["dimension"]: ev["segment"]}, "window_days": 7, "baseline_days": 28,
                "condition": {"pct_change_below": -20}, "every_hours": 24}
        name = f"Watch {ev['dimension']} {ev['segment']} {rule['value'] or 'volume'}"
        desc = f"Daily check that alerts when {ev['dimension']}={ev['segment']} runs >20% below its 4-week baseline."
        steps = ["Call the evaluate endpoint.", "If triggered, post the message to the regional owner.",
                 "Attach the segment breakdown and ask for a cause within 24h."]
        minutes = 30
    elif kind in ("trend", "anomaly"):
        metric = ev["metric"]
        rule = {"type": "anomaly_watch", "time": roles["time"], "value": None if metric == "count" else metric,
                "metric": metric, "every_hours": 24}
        name = f"Anomaly watch on daily {metric}"
        desc = f"Flags days where {metric} deviates from its weekday norm, using a learned threshold."
        steps = ["Call the evaluate endpoint each morning.", "If triggered, check promotions/outages for that date.",
                 "Mark the alert useful or noise in Distill so the threshold self-tunes."]
        minutes = 20
    elif kind == "concentration":
        rule = {"type": "entity_watch", "time": roles["time"], "value": roles["money"], "entity": ev["entity"],
                "top_n": ev["top_n"], "drop_pct": 30, "every_hours": 168}
        name = f"Key {ev['entity']} retention watch"
        desc = f"Weekly list of top {ev['entity']} whose spend fell >30% vs the previous 30 days."
        steps = ["Call the evaluate endpoint weekly.", "Create a CRM task per at-risk account for its owner.",
                 "Log the outcome so retention impact can be measured."]
        minutes = 45
    elif kind == "bottleneck":
        rule = {"type": "sla", "case": roles["case"], "activity": roles["activity"], "time": roles["time"],
                "from_activity": ev["source"], "to_activity": ev["target"],
                "max_hours": round(max(ev["median_hours"] * 0.5, 1), 1), "every_hours": 1}
        name = f"SLA: {ev['source']} to {ev['target']}"
        desc = f"Hourly alert listing cases stuck after '{ev['source']}' longer than {rule['max_hours']}h."
        steps = ["Call the evaluate endpoint hourly.", "Auto-assign listed cases round-robin or ping the lead.",
                 "Track the median wait weekly; tighten max_hours as it improves."]
        minutes = 60
    elif kind == "automation_candidate":
        per_week = stats.get("frequency", 0) / max(stats.get("weeks", 1), 1)
        mins = (ev.get("median_hours_since_previous") or 0.1) * 60
        rule = {"type": "event_bot", "case_field": roles["case"], "activity_field": roles["activity"],
                "time": roles["time"], "trigger_activity": stats.get("predecessor") or "",
                "replaces_activity": ev["name"]}
        name = f"Bot: automate '{ev['name']}'"
        desc = f"Replaces the manual '{ev['name']}' step: runs automatically after '{rule['trigger_activity']}'."
        steps = [f"Listen for '{rule['trigger_activity']}' events (webhook).",
                 "Map the case fields to the target system's schema.",
                 f"Perform '{ev['name']}' via the target system's API and log the result back as an event."]
        minutes = round(per_week * mins, 1)
    elif kind == "rework":
        rule = {"type": "sla", "case": roles["case"], "activity": roles["activity"], "time": roles["time"],
                "from_activity": ev["activity"], "to_activity": None, "max_hours": 24, "every_hours": 6}
        name = f"Auto follow-up after '{ev['activity']}'"
        desc = f"Sends a templated reminder when a case has been waiting >24h after '{ev['activity']}'."
        steps = ["Call the evaluate endpoint every 6 hours.", "Send the follow-up template to each listed case.",
                 "Review which missing fields trigger loops and add them to the intake form."]
        minutes = 40
    else:
        return None
    return {"name": name, "kind": rule["type"], "rule": rule, "description": desc, "steps": steps,
            "minutes": minutes}


def build_artifacts(spec: dict[str, Any], insight_title: str, api_base: str, ref: str) -> tuple[dict, str]:
    wf = n8n_for(spec["rule"], spec["name"], api_base, ref)
    md = skill_for(spec["name"], spec["description"], spec["rule"], insight_title, spec["steps"], api_base, ref)
    return wf, md


# --------------------------------------------------------------------------- runtime evaluation

def evaluate(rule: dict[str, Any], df: pd.DataFrame, thresholds: dict[str, float] | None = None) -> dict[str, Any]:
    if df.empty:
        return {"triggered": False, "message": "no data", "details": {}}
    t = rule["type"]
    if t == "metric_threshold":
        sub = df
        for col, val in (rule.get("filter") or {}).items():
            sub = sub[sub[col].astype(str) == str(val)]
        s = _daily(sub, rule["time"], rule.get("value"))
        w, base_days = rule["window_days"], rule.get("baseline_days", 28)
        recent = s.iloc[-w:].mean()
        baseline = s.iloc[-(w + base_days):-w].mean()
        pct = (recent / baseline - 1) * 100 if baseline else 0.0
        trig = pct < rule["condition"]["pct_change_below"]
        label = ", ".join(f"{k}={v}" for k, v in (rule.get("filter") or {}).items())
        return {"triggered": bool(trig),
                "message": f"{label}: last {w} days {pct:+.1f}% vs the {base_days}-day baseline",
                "details": {"recent_daily": round(float(recent), 2), "baseline_daily": round(float(baseline), 2),
                            "pct": round(float(pct), 2)}}
    if t == "anomaly_watch":
        found = anomalies(df, {"time": rule["time"], "money": rule.get("value")}, thresholds or {})
        found = [f for f in found if f.evidence["metric"] == rule["metric"]]
        last_day = str(pd.to_datetime(df[rule["time"]], utc=True, format="mixed").max().date())
        today = [f for f in found if f.evidence["date"] == last_day]
        return {"triggered": bool(today), "message": today[0].title if today else f"{rule['metric']} normal on {last_day}",
                "details": {"recent_anomalies": [f.evidence["date"] for f in found][-5:]}}
    if t == "entity_watch":
        tt = pd.to_datetime(df[rule["time"]], utc=True, format="mixed", errors="coerce")
        end = tt.max()
        v = pd.to_numeric(df[rule["value"]], errors="coerce")
        recent = v[tt > end - pd.Timedelta(days=30)].groupby(df[rule["entity"]]).sum()
        prior = v[(tt <= end - pd.Timedelta(days=30)) & (tt > end - pd.Timedelta(days=60))].groupby(df[rule["entity"]]).sum()
        top = prior.sort_values(ascending=False).head(rule["top_n"]).index
        at_risk = [{"entity": str(e), "prior": round(float(prior[e]), 2), "recent": round(float(recent.get(e, 0)), 2)}
                   for e in top if recent.get(e, 0) < prior[e] * (1 - rule["drop_pct"] / 100)]
        return {"triggered": bool(at_risk), "message": f"{len(at_risk)} key {rule['entity']} at risk",
                "details": {"at_risk": at_risk[:25]}}
    if t == "sla":
        frame = df[[rule["case"], rule["activity"], rule["time"]]].copy()
        frame["_t"] = pd.to_datetime(frame[rule["time"]], utc=True, format="mixed", errors="coerce")
        now = frame["_t"].max()
        last = frame.sort_values("_t").groupby(rule["case"]).tail(1)
        waiting = last[last[rule["activity"]] == rule["from_activity"]]
        waiting = waiting[(now - waiting["_t"]).dt.total_seconds() / 3600 > rule["max_hours"]]
        cases = waiting[rule["case"]].astype(str).tolist()
        return {"triggered": bool(cases),
                "message": f"{len(cases)} cases waiting > {rule['max_hours']}h after '{rule['from_activity']}'",
                "details": {"cases": cases[:50], "as_of": str(now)}}
    if t == "event_bot":
        model = discover(df, rule["case_field"], rule["activity_field"], rule["time"])
        act = next((a for a in model.get("activities", []) if a["name"] == rule["replaces_activity"]), None)
        n = act["frequency"] if act else 0
        return {"triggered": False, "message": f"Bot would have handled {n} '{rule['replaces_activity']}' steps",
                "details": {"handled": n}}
    raise ValueError(f"unknown rule type {t}")
